// 题目描述
// 求出10至1000之内能同时被2、3、7整除的数，并输出。

// 每行一个。

// 输入格式
// 无
// 输出格式
// 无
// 样例输入
// 无
// 样例输出
// 无
//没有需要输入的变量，循环要做到的是判断和输出
//所以用一个变量即可，循环条件从10到1000
//然后if(((i % 2 == 0) && (i % 3) == 0) && (i % 7 == 0))
#include <stdio.h>

int main()
{
    int num;

    for(int i = 10;i >= 10 && i <= 1000;i++)
    {
        if(((i % 2 == 0) && (i % 3) == 0) && (i % 7 == 0))
        {
            num = i;
            printf("%d\n",num);
        }
    }
    return 0;
}