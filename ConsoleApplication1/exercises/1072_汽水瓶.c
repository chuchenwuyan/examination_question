#include <stdio.h>

int main()
{
    int n;
    int count;
    int drinks;

    while(1)
    {
        scanf("%d",&n);

        if(n == 0)
        {
            break;
        }
        count = 0;
        while(n >= 3)
        {
            drinks = n / 3;
            count += drinks;
            n = drinks + n % 3;
        }
        
        if(n == 2)
        {
            count++;
        }

        printf("%d\n",count);
    }
    return 0;
}